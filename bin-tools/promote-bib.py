def load_sibling(filename: str):
    here = Path(__file__).resolve().parent
    for folder in (here, here.parent / "bin-tools"):
        path = folder / filename
        if path.is_file():
            spec = importlib.util.spec_from_file_location(filename.replace("-", "_")[:-3], path)
            module = importlib.util.module_from_spec(spec)
            sys.modules[spec.name] = module
            spec.loader.exec_module(module)
            return module, path
    raise SystemExit(f"promote-bib: {filename} must be in the same folder as this script")


dd, _ = load_sibling("dedup-bib.py")

VERSION = "1.0.0"
STAMP_FIELD = "verified"
STAMP_RE = re.compile(r"^\s*([a-z]+(?:\+[a-z]+)*)\s*;\s*(\d{4}-\d{2}-\d{2})\s*;\s*fp=([0-9a-f]{10})\s*$")
DEFAULT_AI_TAG = r"^generated_by_"
AI_NOTE_RE = re.compile(r"generated by", re.IGNORECASE)
ALLOWED_STATUS = ("VERIFIED",)

OK, STALE, MALFORMED, UNSTAMPED, HUMAN = "ok", "stale", "malformed", "unstamped", "human"
PROBLEMS = (STALE, MALFORMED, UNSTAMPED)

IS_TTY = sys.stdin.isatty() and sys.stdout.isatty()


