#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
promote-bib.py — A verification gate for AI-generated BibTeX entries.

The idea: an AI agent may PROPOSE entries (they land in a candidate file such
as ai_slop/*.bib); tools VERIFY them against Crossref and OpenAlex; only
verified entries are PROMOTED into the curated files; and CI makes sure nothing
AI-generated sits in a curated file without proof of verification.

Three subcommands:

  stamp    Read the JSON that `verify-bib.py --json` produced (or run
           verify-bib.py itself with --verify) and add a `verified` field to
           every entry that verified cleanly:

               verified = {crossref+openalex; 2026-11-20; fp=3fa91c07d2}

           It names the registries that found the work, the date, and a
           fingerprint of the entry's identity (title, author surnames, year,
           DOI). Change any of those afterwards and the stamp no longer fits.

  check    The CI gate. Fails (exit 2) when a file contains
             * an AI-generated entry with no stamp          (UNSTAMPED),
             * a stamp whose fingerprint no longer matches   (STALE: edited
               after verification), or
             * a stamp that cannot be read                   (MALFORMED).
           An entry counts as AI-generated when its `comment` tags match
           --ai-tag (default `generated_by_*`) or its `note` says "Generated by".
           Entries by humans are only checked when they carry a stamp.

  promote  Move the entries of a candidate file that carry a valid stamp into a
           curated file. Entries already in the curated file (same work, as
           judged by dedup-bib.py) are skipped, and different works with the
           same key are reported, never overwritten. Unstamped entries stay
           where they are.

Only AI-generated entries are stamped (add --all for every verified entry).
Only identity is stamped. An abstract, a note or a tag can be edited freely
without breaking a stamp, and the stamp says nothing about them.

Files are edited as text, so only the touched entries change. Dry run is the
default for `stamp` and `promote`; pass --apply to write (a .bak backup is made
first). The result is re-parsed and checked before anything is written.

This script reuses the matching and text-editing code of dedup-bib.py, which
must sit in the same folder.

Exit codes:
  0  success
  1  error (unreadable file, failed safety check, write failure, bad report)
  2  `check` found a problem
"""

