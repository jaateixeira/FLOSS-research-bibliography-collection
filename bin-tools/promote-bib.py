@dataclass
class Loaded:
    path: Path
    text: str
    items: list
    skipped: int


def load_file(path: Path) -> Loaded:
    text = dd.read_text(path)
    items, skipped, err = dd.load_items(text, str(path))
    if err:
        raise ValueError(f"{path}: {err}")
    return Loaded(path, text, items, skipped)


def patched_entry(raw: str, replace: dict[str, str], add: list[tuple[str, str]]) -> Optional[str]:
    """dd.patch_entry_text, accepted only when the result still parses as one entry."""
    new = dd.patch_entry_text(raw, replace, add)
    if new is None:
        return None
    lib = dd.bibtexparser.parse_string(new)
    return new if len(lib.entries) == 1 and not lib.failed_blocks else None


def apply_edits(text: str, edits: list[tuple[int, int, str]]) -> str:
    nl = "\r\n" if "\r\n" in text else "\n"
    for start, end, repl in sorted(edits, key=lambda e: e[0], reverse=True):
        text = text[:start] + repl.replace("\r\n", "\n").replace("\n", nl) + text[end:]
    return text


def remove_items(text: str, items: list) -> str:
    """Cut entries out with dedup-bib's own cutting code (blank lines, EOF, CRLF)."""
    if not items:
        return text
    cut = dd.Cluster(primary=items[0], removed=list(items), reasons=[])   # nothing is kept or changed
    return dd.apply_clusters(text, [cut])


def write_with_backup(path: Path, new_text: str, backup: bool) -> Optional[str]:
    if backup:
        try:
            shutil.copy2(path, path.with_name(path.name + ".bak"))
        except OSError as e:
            return f"backup failed: {e}"
    try:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(new_text)
    except OSError as e:
        return f"write failed: {e}"
    return None


