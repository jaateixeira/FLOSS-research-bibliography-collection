@dataclass
class PromotePlan:
    movable: list = field(default_factory=list)
    already: list = field(default_factory=list)        # (item, matching target item)
    collisions: list = field(default_factory=list)     # (item, target item)
    waiting: list = field(default_factory=list)        # (item, status)


def plan_promotion(cand: Loaded, target: Loaded, tag_re: re.Pattern, thr: float) -> PromotePlan:
    plan = PromotePlan()
    stamped = []
    for it in cand.items:
        status = stamp_status(it, tag_re)
        if it.from_failed:
            plan.waiting.append((it, "second copy of a key — run dedup-bib.py first"))
        elif status == OK:
            stamped.append(it)
        else:
            plan.waiting.append((it, status))

    combined = list(target.items) + stamped
    matches, reviews = dd.find_matches(combined, thr=thr, use_key=True)
    in_target = {id(i) for i in target.items}
    dup_of: dict[int, object] = {}
    for m in matches:
        for mine, other in ((m.a, m.b), (m.b, m.a)):
            if id(mine) not in in_target and id(other) in in_target:
                dup_of.setdefault(id(mine), other)
    clash: dict[int, object] = {}
    for r in reviews:
        if not r.collision:
            continue
        a, b = r.items
        for mine, other in ((a, b), (b, a)):
            if id(mine) not in in_target and id(other) in in_target:
                clash.setdefault(id(mine), other)

    seen_keys = {i.key.lower() for i in target.items}
    for it in stamped:
        if id(it) in dup_of:
            plan.already.append((it, dup_of[id(it)]))
        elif id(it) in clash:
            plan.collisions.append((it, clash[id(it)]))
        elif it.key.lower() in seen_keys:
            plan.collisions.append((it, next(t for t in target.items if t.key.lower() == it.key.lower())))
        else:
            plan.movable.append(it)
            seen_keys.add(it.key.lower())
    return plan


def append_entries(text: str, items: list) -> str:
    nl = "\r\n" if "\r\n" in text else "\n"
    body = (nl + nl).join(i.raw.replace("\r\n", "\n").replace("\n", nl) for i in items)
    return text.rstrip() + nl + nl + body + nl if text.strip() else body + nl


def cmd_promote(args) -> int:
    tag_re = re.compile(args.ai_tag)
    try:
        cand, target = load_file(args.candidate), load_file(args.to)
    except (OSError, UnicodeDecodeError, ValueError) as e:
        dd.log.error(esc(str(e)))
        return 1
    if cand.path.resolve() == target.path.resolve():
        dd.log.error("the candidate file and --to must be different files.")
        return 1

    plan = plan_promotion(cand, target, tag_re, args.title_threshold)
    show_plan(plan, cand.path.name, target.path.name)

    drop = [i for i, _ in plan.already] if args.drop_duplicates else []
    leaving = list(plan.movable) + drop
    if not leaving or not args.apply:
        if plan.movable and not args.apply:
            dd.log.info("[yellow]Dry run — nothing written.[/] Re-run with --apply.")
        return 0

    new_target = append_entries(target.text, plan.movable) if plan.movable else target.text
    new_cand = remove_items(cand.text, leaving) if not args.copy else cand.text
    problems = check_promotion(new_target, new_cand, cand, target, plan, tag_re, args.copy, drop)
    if problems:
        dd.log.error("safety check failed — nothing written:")
        for p in problems:
            dd.log.error("  " + esc(p))
        return 1

    for path, text in ((target.path, new_target), (cand.path, new_cand)):
        if text == (target.text if path == target.path else cand.text):
            continue
        err = write_with_backup(path, text, backup=not args.no_backup)
        if err:
            dd.log.error(f"[cyan]{esc(str(path))}[/] {esc(err)}")
            return 1
        dd.log.info(f"[green]Wrote[/] [cyan]{esc(str(path))}[/].")
    dd.log.info(f"{len(plan.movable)} entr{'y' if len(plan.movable) == 1 else 'ies'} promoted"
                + (f", {len(drop)} duplicate(s) dropped from the candidate file" if drop else "") + ".")
    return 0


def check_promotion(new_target, new_cand, cand, target, plan, tag_re, copy, drop) -> list[str]:
    problems = []
    t_items, t_skip, err = dd.load_items(new_target, str(target.path))
    if err:
        return [err]
    c_items, c_skip, err = dd.load_items(new_cand, str(cand.path))
    if err:
        return [err]
    if len(t_items) != len(target.items) + len(plan.movable):
        problems.append("the curated file does not have the expected number of entries")
    expected = len(cand.items) - (0 if copy else len(plan.movable)) - len(drop)
    if len(c_items) != expected:
        problems.append("the candidate file does not have the expected number of entries")
    if t_skip != target.skipped or c_skip != cand.skipped:
        problems.append("the number of unexamined blocks changed")
    after = {i.key.lower(): i for i in t_items}
    for it in plan.movable:
        got = after.get(it.key.lower())
        if got is None or stamp_status(got, tag_re) != OK:
            problems.append(f"'{it.key}' did not arrive with a valid stamp")
    return problems


def show_plan(plan: PromotePlan, cand_name: str, target_name: str) -> None:
    t = Table(title=f"Promotion: {cand_name} → {target_name}", header_style="bold")
    t.add_column("Outcome")
    t.add_column("Entries", justify="right")
    t.add_row(Text("will be promoted", style="green"), str(len(plan.movable)))
    t.add_row("already in the curated file", str(len(plan.already)))
    t.add_row(Text("key collisions", style="bold red" if plan.collisions else ""), str(len(plan.collisions)))
    waiting: dict[str, int] = {}
    for _, why in plan.waiting:
        waiting[why] = waiting.get(why, 0) + 1
    for why, n in sorted(waiting.items(), key=lambda kv: -kv[1]):
        t.add_row(Text(f"stays: {why}", style="yellow"), str(n))
    dd.console.print()
    dd.console.print(t)
    for it, other in plan.collisions[:20]:
        dd.log.warning(f"[cyan]{esc(it.key)}[/] has the same key as a different work in the curated file "
                       f"(line {other.line}); not promoted — rename one.")
    if plan.movable and dd.log.verbose:
        for it in plan.movable:
            dd.console.print(f"  [green]+[/] {esc(it.key)}")


