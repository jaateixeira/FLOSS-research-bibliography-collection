@dataclass
class StampRow:
    key: str
    line: int
    action: str            # stamped | restamped | kept | skipped
    detail: str = ""


def load_report(path: Path) -> dict[tuple[str, str], dict]:
    """verify-bib --json  ->  {(resolved file, lower-case key): entry result}"""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        out = {}
        for f in data["files"]:
            for e in f["entries"]:
                out[(str(Path(f["path"]).resolve()), e["key"].lower())] = e
        return out
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise ValueError(f"cannot use verification report {path}: {e}")


def run_verify(files: list[Path], extra: list[str]) -> dict[tuple[str, str], dict]:
    """Run verify-bib.py on the files and read its JSON from stdout."""
    _, script = load_sibling("verify-bib.py")
    proc = subprocess.run([sys.executable, str(script), *map(str, files), "--json", *extra],
                          capture_output=True, text=True)
    if proc.returncode not in (0, 2):
        raise ValueError(f"verify-bib.py failed (exit {proc.returncode}): {proc.stderr.strip()[-300:]}")
    tmp = Path(os.environ.get("TMPDIR", "/tmp")) / f"promote-bib-{os.getpid()}.json"
    tmp.write_text(proc.stdout, encoding="utf-8")
    try:
        return load_report(tmp)
    finally:
        tmp.unlink(missing_ok=True)


def sources_found(entry: dict) -> list[str]:
    return sorted(name for name, r in (entry.get("sources") or {}).items() if r.get("state") == "found")


def plan_stamps(loaded: Loaded, report: dict, tag_re: re.Pattern, date: str,
                allow_warn: bool, restamp: bool, stamp_all: bool = False) -> tuple[list[tuple[int, int, str]], list[StampRow]]:
    allowed = ALLOWED_STATUS + (("WARN",) if allow_warn else ())
    edits, rows = [], []
    resolved = str(loaded.path.resolve())
    for it in loaded.items:
        status = stamp_status(it, tag_re)
        if it.from_failed:
            rows.append(StampRow(it.key, it.line, "skipped", "second copy of a key — run dedup-bib.py first"))
            continue
        if status == OK and not restamp:
            rows.append(StampRow(it.key, it.line, "kept", "already stamped"))
            continue
        if status == HUMAN and not stamp_all:
            rows.append(StampRow(it.key, it.line, "kept", "not AI-generated (use --all to stamp it)"))
            continue
        entry = report.get((resolved, it.key.lower()))
        if entry is None:
            rows.append(StampRow(it.key, it.line, "skipped", "not in the verification report"))
            continue
        if entry.get("status") not in allowed:
            rows.append(StampRow(it.key, it.line, "skipped", f"verify-bib says {entry.get('status')}"))
            continue
        found = sources_found(entry)
        if not found:
            rows.append(StampRow(it.key, it.line, "skipped", "no registry found it"))
            continue
        stamp = make_stamp(found, date, fingerprint(it))
        if STAMP_FIELD in it.fields:
            new = patched_entry(it.raw, {STAMP_FIELD: stamp}, [])
        else:
            new = patched_entry(it.raw, {}, [(STAMP_FIELD, stamp)])
        if new is None:
            rows.append(StampRow(it.key, it.line, "skipped", "entry formatting cannot be patched safely"))
            continue
        edits.append((it.start, it.end, new))
        rows.append(StampRow(it.key, it.line, "restamped" if status != UNSTAMPED and STAMP_FIELD in it.fields
                             else "stamped", "+".join(found)))
    return edits, rows


def check_stamped_text(new_text: str, before: Loaded, tag_re: re.Pattern, expect: set[str]) -> list[str]:
    items, skipped, err = dd.load_items(new_text, str(before.path))
    if err:
        return [err]
    problems = []
    if len(items) != len(before.items) or skipped != before.skipped:
        problems.append("the number of entries or unexamined blocks changed")
    for it in items:
        if it.key.lower() in expect and stamp_status(it, tag_re) != OK:
            problems.append(f"'{it.key}' does not carry a valid stamp after stamping")
    return problems


def cmd_stamp(args) -> int:
    tag_re = re.compile(args.ai_tag)
    files = list(args.bibfiles)
    try:
        report = load_report(args.report) if args.report else run_verify(files, [])
    except ValueError as e:
        dd.log.error(esc(str(e)))
        return 1

    date = args.date or datetime.date.today().isoformat()
    total = {"stamped": 0, "restamped": 0, "kept": 0, "skipped": 0}
    failed = False
    for path in files:
        try:
            loaded = load_file(path)
        except (OSError, UnicodeDecodeError, ValueError) as e:
            dd.log.error(esc(str(e)))
            failed = True
            continue
        edits, rows = plan_stamps(loaded, report, tag_re, date, args.allow_warn, args.restamp, args.all)
        for r in rows:
            total[r.action] += 1
        show_stamp_rows(path.name, rows, args.verbose)
        if not edits or not args.apply:
            continue
        new_text = apply_edits(loaded.text, edits)
        expect = {r.key.lower() for r in rows if r.action in ("stamped", "restamped")}
        problems = check_stamped_text(new_text, loaded, tag_re, expect)
        if problems:
            dd.log.error(f"[cyan]{esc(path.name)}[/] safety check failed — not written: " + esc("; ".join(problems)))
            failed = True
            continue
        err = write_with_backup(path, new_text, backup=not args.no_backup)
        if err:
            dd.log.error(f"[cyan]{esc(str(path))}[/] {esc(err)}")
            failed = True
            continue
        dd.log.info(f"[green]Wrote[/] [cyan]{esc(str(path))}[/] ({len(edits)} stamp(s)).")

    n = total["stamped"] + total["restamped"]
    dd.log.info(f"{n} entr{'y' if n == 1 else 'ies'} {'stamped' if args.apply else 'to stamp'}, "
                f"{total['kept']} left as they were, {total['skipped']} skipped.")
    if n and not args.apply:
        dd.log.info("[yellow]Dry run — nothing written.[/] Re-run with --apply.")
    return 1 if failed else 0


def show_stamp_rows(name: str, rows: list[StampRow], verbose: bool) -> None:
    shown = [r for r in rows if r.action in ("stamped", "restamped") or (verbose and r.action != "kept")
             or r.action == "skipped" and "report" not in r.detail]
    dd.console.print()
    if not shown:
        dd.console.print(f"[dim]{esc(name)}: nothing to stamp.[/]")
        return
    t = Table(title=f"Stamps — {name}", header_style="bold")
    t.add_column("Key", style="cyan", overflow="fold")
    t.add_column("Action")
    t.add_column("Detail", overflow="fold")
    style = {"stamped": "green", "restamped": "green", "skipped": "yellow"}
    for r in shown[:200]:
        t.add_row(r.key, Text(r.action, style=style.get(r.action, "")), r.detail)
    if len(shown) > 200:
        t.caption = f"{len(shown) - 200} more not shown"
    dd.console.print(t)


