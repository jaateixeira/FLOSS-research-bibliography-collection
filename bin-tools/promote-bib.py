def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="promote-bib",
        description="Verification gate for AI-generated BibTeX entries: stamp, check, promote.")
    p.add_argument("--verbose", "-v", action="store_true", help="Verbose output")
    sub = p.add_subparsers(dest="command", required=True)

    def common(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--ai-tag", default=DEFAULT_AI_TAG, metavar="REGEX",
                        help=f"Regex for `comment` tags that mark AI-generated entries "
                             f"(default {DEFAULT_AI_TAG!r})")

    def writing(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--apply", action="store_true", help="Write the changes (dry run otherwise)")
        sp.add_argument("--no-backup", action="store_true", help="No .bak files when writing")

    s = sub.add_parser("stamp", help="Stamp entries that verify-bib verified")
    s.add_argument("bibfiles", nargs="+", type=Path)
    s.add_argument("--report", type=Path, metavar="VERIFY.json",
                   help="Output of `verify-bib.py --json` (otherwise use --verify)")
    s.add_argument("--verify", action="store_true",
                   help="Run verify-bib.py now (needs network; reads $OPENALEX_API_KEY, $CROSSREF_MAILTO)")
    s.add_argument("--allow-warn", action="store_true",
                   help="Also stamp entries verify-bib rated WARN (default: VERIFIED only)")
    s.add_argument("--restamp", action="store_true", help="Replace stamps that are already valid")
    s.add_argument("--all", action="store_true",
                   help="Stamp every verified entry, not only AI-generated ones")
    s.add_argument("--date", metavar="YYYY-MM-DD", help="Date to record (default today)")
    common(s)
    writing(s)

    c = sub.add_parser("check", help="Gate: fail if AI-generated entries lack a valid stamp")
    c.add_argument("bibfiles", nargs="+", type=Path)
    c.add_argument("--json", action="store_true", help="Machine-readable output on stdout")
    c.add_argument("--report", type=Path, metavar="FILE.md", help="Write a Markdown report")
    c.add_argument("--gha", action="store_true", help="GitHub Actions annotations and step summary")
    common(c)

    m = sub.add_parser("promote", help="Move stamped entries from a candidate file to a curated one")
    m.add_argument("candidate", type=Path, help="File holding the proposed entries (e.g. ai_slop/x.bib)")
    m.add_argument("--to", type=Path, required=True, metavar="CURATED.bib", help="Curated file to add to")
    m.add_argument("--copy", action="store_true", help="Leave the entries in the candidate file too")
    m.add_argument("--drop-duplicates", action="store_true",
                   help="Also remove from the candidate file entries the curated file already has")
    m.add_argument("--title-threshold", type=float, default=dd.TITLE_THRESHOLD)
    common(m)
    writing(m)
    return p


def main(argv: Optional[list[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    json_out = getattr(args, "json", False)
    console = Console(stderr=json_out, no_color=not IS_TTY, highlight=False)
    dd.setup_logging(args.verbose, output_console=console)

    try:
        re.compile(args.ai_tag)
    except re.error as e:
        dd.log.error(f"--ai-tag is not a valid regex: {esc(str(e))}")
        return 1

    paths = list(getattr(args, "bibfiles", [])) + [p for p in (getattr(args, "candidate", None),
                                                               getattr(args, "to", None)) if p]
    for f in paths:
        if f.suffix.lower() != ".bib" or not f.is_file():
            dd.log.error(f"not a .bib file: [cyan]{esc(str(f))}[/]")
            return 1

    if args.command == "stamp":
        if bool(args.report) == bool(args.verify):
            dd.log.error("give exactly one of --report VERIFY.json or --verify.")
            return 1
        if args.date and not re.match(r"^\d{4}-\d{2}-\d{2}$", args.date):
            dd.log.error("--date must look like 2026-11-20.")
            return 1
        mode = "apply" if args.apply else "dry run"
    elif args.command == "promote":
        mode = "apply" if args.apply else "dry run"
    else:
        mode = "read-only"
    console.print(Panel(f"[bold]Command:[/] {args.command}\n[bold]Mode:[/] {mode}",
                        title="[bold blue]promote-bib[/]", expand=False))

    return {"stamp": cmd_stamp, "check": cmd_check, "promote": cmd_promote}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
