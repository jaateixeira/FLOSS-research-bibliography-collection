# Stamps
# =============================================================================

def fingerprint(item) -> str:
    """Identity of a work: normalised title, author surnames, year, DOI."""
    basis = "|".join([item.title_key, ",".join(item.surnames), item.year, item.doi])
    return hashlib.sha1(basis.encode("utf-8")).hexdigest()[:10]


def make_stamp(sources: list[str], date: str, fp: str) -> str:
    return f"{'+'.join(sorted(sources))}; {date}; fp={fp}"


def parse_stamp(value: str) -> Optional[tuple[str, str, str]]:
    m = STAMP_RE.match(value or "")
    return (m.group(1), m.group(2), m.group(3)) if m else None


def is_ai(item, tag_re: re.Pattern) -> bool:
    return any(tag_re.search(t) for t in item.tags) or bool(AI_NOTE_RE.search(item.fields.get("note", "")))


def stamp_status(item, tag_re: re.Pattern) -> str:
    raw = item.fields.get(STAMP_FIELD, "")
    if raw.strip():
        parsed = parse_stamp(raw)
        if parsed is None:
            return MALFORMED
        return OK if parsed[2] == fingerprint(item) else STALE
    return UNSTAMPED if is_ai(item, tag_re) else HUMAN


