def cmd_check(args) -> int:
    tag_re = re.compile(args.ai_tag)
    problems = []
    counts = {OK: 0, HUMAN: 0, STALE: 0, MALFORMED: 0, UNSTAMPED: 0}
    fatal = False
    for path in args.bibfiles:
        try:
            loaded = load_file(path)
        except (OSError, UnicodeDecodeError, ValueError) as e:
            dd.log.error(esc(str(e)))
            fatal = True
            continue
        for it in loaded.items:
            status = stamp_status(it, tag_re)
            counts[status] += 1
            if status in PROBLEMS:
                problems.append((str(path), it, status))
                if args.gha:
                    dd.gha_annotate("error", f"{it.key}: {status.upper()} — " + MESSAGE[status],
                                    file=str(path), line=it.line)

    if problems:
        t = Table(title="Entries that fail the gate", header_style="bold")
        t.add_column("File", overflow="fold")
        t.add_column("Key", style="cyan", overflow="fold")
        t.add_column("Problem", style="red")
        t.add_column("What to do", overflow="fold")
        for path, it, status in problems[:300]:
            t.add_row(Path(path).name, it.key, status.upper(), MESSAGE[status])
        if len(problems) > 300:
            t.caption = f"{len(problems) - 300} more not shown (see --json)"
        dd.console.print()
        dd.console.print(t)

    summary = Table(title="Gate summary", header_style="bold")
    summary.add_column("")
    summary.add_column("Entries", justify="right")
    summary.add_row("Stamped and valid", str(counts[OK]))
    summary.add_row("Human entries, no stamp needed", str(counts[HUMAN]))
    for s in PROBLEMS:
        summary.add_row(Text(s.upper(), style="bold red" if counts[s] else ""), str(counts[s]))
    dd.console.print()
    dd.console.print(summary)

    md = gate_markdown(problems, counts)
    if args.report:
        args.report.write_text(md, encoding="utf-8")
    if args.gha:
        dd.write_gha_summary(md)
    if args.json:
        print(json.dumps({
            "counts": counts,
            "problems": [{"file": p, "key": it.key, "line": it.line, "problem": s}
                         for p, it, s in problems],
        }, indent=2))
    if fatal:
        return 1
    if problems:
        dd.log.error(f"{len(problems)} entr{'y' if len(problems) == 1 else 'ies'} fail the gate.")
        return 2
    dd.log.info("[green]Gate passed.[/]")
    return 0


MESSAGE = {
    UNSTAMPED: "AI-generated and never verified: run verify-bib.py, then `promote-bib.py stamp`",
    STALE: "title, authors, year or DOI changed after verification: verify and stamp again",
    MALFORMED: "the `verified` field cannot be read: restamp with --restamp",
}


def gate_markdown(problems, counts) -> str:
    out = ["## promote-bib gate\n\n",
           f"{counts[OK]} stamped and valid, {counts[HUMAN]} human entries, "
           f"{len(problems)} failing.\n\n"]
    if problems:
        out.append("| File | Key | Problem |\n|---|---|---|\n")
        for path, it, status in problems:
            out.append(f"| `{path}` | `{it.key}` | {status.upper()} |\n")
        out.append("\n")
    return "".join(out)


