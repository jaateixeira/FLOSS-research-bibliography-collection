def test_verify_option_runs_verify_bib_and_reads_its_json(tmp_path, monkeypatch):
    path = write(tmp_path, "c.bib", AI)
    calls = []

    class Done:
        returncode = 0
        stdout = json.dumps(report(path, {"ai1": "VERIFIED"}))
        stderr = ""

    monkeypatch.setattr(pb.subprocess, "run", lambda cmd, **kw: calls.append(cmd) or Done())
    assert pb.main(["stamp", str(path), "--verify", "--apply", "--no-backup"]) == 0
    assert calls and "--json" in calls[0] and calls[0][1].endswith("verify-bib.py")
    assert "verified" in items(read(path))["ai1"].fields


