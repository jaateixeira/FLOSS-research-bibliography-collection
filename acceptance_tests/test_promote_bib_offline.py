def test_warn_needs_allow_warn(tmp_path):
    path = write(tmp_path, "c.bib", AI)
    rp = write_report(tmp_path, path, {"ai1": "WARN"})
    pb.main(["stamp", str(path), "--report", str(rp), "--apply", "--no-backup"])
    assert "verified" not in items(read(path))["ai1"].fields
    pb.main(["stamp", str(path), "--report", str(rp), "--apply", "--no-backup", "--allow-warn"])
