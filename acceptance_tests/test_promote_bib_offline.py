def test_stamp_apply_makes_a_backup(tmp_path):
    path = write(tmp_path, "c.bib", AI)
    rp = write_report(tmp_path, path, ALL_OK)
    assert pb.main(["stamp", str(path), "--report", str(rp), "--apply"]) == 0
