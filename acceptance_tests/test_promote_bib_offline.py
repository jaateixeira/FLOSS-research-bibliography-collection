def test_fingerprint_follows_identity_not_wording():
    base = items(AI)["ai1"]
    reformatted = items(AI.replace("Smith, Anna and Lee, Bo", "Anna Smith and Bo Lee")
                          .replace("[Paraphrase] A study of forks.", "Something else entirely")
                          .replace("Journal of Examples", "Another Journal"))["ai1"]
    assert pb.fingerprint(base) == pb.fingerprint(reformatted)
    for old, new in (("Forking and governance", "Forking or governance"), ("2024", "2025"),
                     ("10.1000/ai1", "10.1000/ai9"), ("Smith, Anna", "Brown, Anna")):
        assert pb.fingerprint(base) != pb.fingerprint(items(AI.replace(old, new))["ai1"]), old


def test_stamp_round_trip():
    s = pb.make_stamp(["openalex", "crossref"], "2026-11-20", "0123456789")
    assert s == "crossref+openalex; 2026-11-20; fp=0123456789"
    assert pb.parse_stamp(s) == ("crossref+openalex", "2026-11-20", "0123456789")
    assert pb.parse_stamp("yes") is None and pb.parse_stamp("") is None


def test_ai_detection_by_tag_and_by_note():
    its = items(AI)
    assert pb.is_ai(its["ai1"], TAG) and pb.is_ai(its["ai3"], TAG) and not pb.is_ai(its["human1"], TAG)
    by_note = items("@article{n, author={A, B}, title={Some title here for testing}, year={2020}, "
                    "note={generated by GPT}}")["n"]
    assert pb.is_ai(by_note, TAG)


def test_stamp_status_values(tmp_path):
    path = stamped_file(tmp_path)
    its = items(read(path))
    assert pb.stamp_status(its["ai1"], TAG) == pb.OK
    assert pb.stamp_status(its["ai3"], TAG) == pb.UNSTAMPED
    assert pb.stamp_status(its["human1"], TAG) == pb.HUMAN
    stale = items(read(path).replace("Forking and governance", "Forking or governance"))["ai1"]
    assert pb.stamp_status(stale, TAG) == pb.STALE
    broken = items(re.sub(r"verified = \{[^}]*\}", "verified = {yes}", read(path)))["ai1"]
    assert pb.stamp_status(broken, TAG) == pb.MALFORMED


