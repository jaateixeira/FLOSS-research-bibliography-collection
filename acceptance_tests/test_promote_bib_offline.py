def test_only_verified_entries_are_stamped(tmp_path):
    text = read(stamped_file(tmp_path))
    its = items(text)
    assert "verified" in its["ai1"].fields and "verified" in its["ai2"].fields
    assert "verified" not in its["ai3"].fields and "verified" not in its["human1"].fields
    assert its["ai1"].fields["verified"] == f"crossref+openalex; 2026-11-20; fp={pb.fingerprint(its['ai1'])}"


def test_stamp_changes_nothing_else(tmp_path):
    text = read(stamped_file(tmp_path))
    before, after = items(AI), items(text)
    for key in before:
        assert {k: v for k, v in after[key].fields.items() if k != "verified"} == before[key].fields
    assert text.count("@article") == AI.count("@article")
    assert text[text.index("@article{ai3"):] == AI[AI.index("@article{ai3"):]    # untouched tail, byte for byte


