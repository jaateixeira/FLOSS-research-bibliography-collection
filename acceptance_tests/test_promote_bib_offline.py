def test_gate_catches_edits_after_verification_but_not_harmless_ones(tmp_path, capsys):
    path = stamped_file(tmp_path)
    text = read(path)
    capsys.readouterr()                                              # drop the stamping output
    harmless = text.replace("[Paraphrase] A study of forks.", "A different abstract").replace(
        "Journal of Examples", "Other Journal").replace("Smith, Anna and Lee, Bo", "Anna Smith and Bo Lee")
    path.write_text(harmless, encoding="utf-8")
    pb.main(["check", str(path), "--json"])
    assert json.loads(capsys.readouterr().out)["counts"]["stale"] == 0
    path.write_text(text.replace("10.1000/ai2", "10.1000/zzz"), encoding="utf-8")
    assert pb.main(["check", str(path), "--json"]) == 2
    out = json.loads(capsys.readouterr().out)
    assert [(p["key"], p["problem"]) for p in out["problems"] if p["problem"] == "stale"] == [("ai2", "stale")]


def test_gate_gha_and_report(tmp_path, capsys, monkeypatch):
    path = write(tmp_path, "c.bib", AI)
    monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(tmp_path / "s.md"))
    md = tmp_path / "gate.md"
    assert pb.main(["check", str(path), "--gha", "--report", str(md)]) == 2
    out = capsys.readouterr().out
    assert "::error file=" in out and "UNSTAMPED" in out
    assert "## promote-bib gate" in (tmp_path / "s.md").read_text(encoding="utf-8")
    assert "`ai1`" in md.read_text(encoding="utf-8")


