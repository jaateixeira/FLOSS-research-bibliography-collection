def report(path: Path, statuses: dict[str, str], sources=("crossref", "openalex")) -> dict:
    return {"files": [{"path": str(path), "entries": [
        {"key": k, "status": s,
         "sources": {src: {"state": "found" if s != "NOT_FOUND" else "not_found"} for src in sources}}
        for k, s in statuses.items()]}]}


def write(tmp_path: Path, name: str, text: str, newline: str = "") -> Path:
    path = tmp_path / name
    with open(path, "w", encoding="utf-8", newline=newline) as f:
        f.write(text)
    return path


def read(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def write_report(tmp_path: Path, path: Path, statuses: dict[str, str]) -> Path:
    rp = tmp_path / "verify.json"
    rp.write_text(json.dumps(report(path, statuses)), encoding="utf-8")
    return rp


def items(text: str):
    its, _, err = dd.load_items(text, "t.bib")
    assert err is None
    return {i.key: i for i in its}


ALL_OK = {"ai1": "VERIFIED", "ai2": "VERIFIED", "ai3": "NOT_FOUND", "human1": "VERIFIED"}


def stamped_file(tmp_path: Path, name: str = "cand.bib", text: str = AI) -> Path:
    path = write(tmp_path, name, text)
    rp = write_report(tmp_path, path, {"ai1": "VERIFIED", "ai2": "VERIFIED", "ai3": "NOT_FOUND"})
    assert pb.main(["stamp", str(path), "--report", str(rp), "--apply", "--no-backup",
                    "--date", "2026-11-20"]) == 0
    return path


