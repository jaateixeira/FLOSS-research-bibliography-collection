CURATED = r"""@article{old1,
  author = {Old, Olga},
  title  = {A paper that was already in the curated file},
  year   = {2015},
  doi    = {10.1000/old1}
}
"""


def promote_setup(tmp_path):
    cand = stamped_file(tmp_path)
    cur = write(tmp_path, "cur.bib", CURATED)
    return cand, cur


def test_promote_moves_only_stamped_entries(tmp_path):
    cand, cur = promote_setup(tmp_path)
    assert pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup"]) == 0
    c, t = items(read(cand)), items(read(cur))
    assert set(t) == {"old1", "ai1", "ai2"} and set(c) == {"ai3", "human1"}
    assert t["ai1"].fields["verified"] == items(AI)["ai1"].fields.get("verified", t["ai1"].fields["verified"])
    assert pb.main(["check", str(cur)]) == 0                         # arrives with a valid stamp
    assert read(cur).startswith(CURATED.rstrip()) and read(cur).endswith("}\n")


def test_promote_dry_run_and_backups(tmp_path):
    cand, cur = promote_setup(tmp_path)
    before = (read(cand), read(cur))
    assert pb.main(["promote", str(cand), "--to", str(cur)]) == 0
    assert (read(cand), read(cur)) == before
    pb.main(["promote", str(cand), "--to", str(cur), "--apply"])
    assert read(tmp_path / "cand.bib.bak") == before[0] and read(tmp_path / "cur.bib.bak") == before[1]


def test_promote_copy_keeps_the_candidate_intact(tmp_path):
    cand, cur = promote_setup(tmp_path)
    before = read(cand)
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup", "--copy"])
    assert read(cand) == before and "ai1" in items(read(cur))


def test_promote_skips_works_the_curated_file_already_has(tmp_path):
    cand, cur = promote_setup(tmp_path)
    write(tmp_path, "cur.bib", CURATED + "\n@article{Someone2024,\n  author = {Lee, Bo and Smith, Anna},\n"
          "  title = {Forking and governance in open source ecosystems},\n  year = {2024},\n  doi = {10.1000/AI1}\n}\n")
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup"])
    t, c = items(read(cur)), items(read(cand))
    assert "ai1" not in t and "ai2" in t and "ai1" in c              # the duplicate stays behind
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup", "--drop-duplicates"])
    assert "ai1" not in items(read(cand))


def test_promote_never_overwrites_a_key_that_means_something_else(tmp_path):
    cand, _ = promote_setup(tmp_path)
    cur = write(tmp_path, "cur2.bib", CURATED.replace("old1", "ai1"))
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup"])
    assert items(read(cur))["ai1"].fields["title"].startswith("A paper that was already")
    assert "ai1" in items(read(cand)) and "ai2" in items(read(cur))


def test_promote_refuses_the_same_file_and_bad_input(tmp_path):
    cand, cur = promote_setup(tmp_path)
    assert pb.main(["promote", str(cand), "--to", str(cand)]) == 1
    assert pb.main(["promote", str(cand), "--to", str(tmp_path / "missing.bib")]) == 1


def test_promote_keeps_crlf_files_consistent(tmp_path):
    cand = stamped_file(tmp_path)
    cur = write(tmp_path, "crlf.bib", CURATED.replace("\n", "\r\n"))
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup"])
    out = read(cur)
    assert "ai1" in items(out) and "\n" not in out.replace("\r\n", "")


def test_promote_into_an_empty_curated_file(tmp_path):
    cand = stamped_file(tmp_path)
    cur = write(tmp_path, "empty.bib", "")
    pb.main(["promote", str(cand), "--to", str(cur), "--apply", "--no-backup"])
    assert set(items(read(cur))) == {"ai1", "ai2"}
